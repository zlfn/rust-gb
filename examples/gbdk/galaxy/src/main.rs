// C original: const unsigned char * const film[25] = { &door1_tiles[0x0C*0], ... }
// Rust can't store raw pointers in statics (not Sync), so we compute at call site.
unsafe fn film(pos: u8) -> *const u8 {
    let offset = (pos as usize / 4) * 0x0C;
    match pos % 4 {
        0 => DOOR1_TILES.as_ptr().add(offset),
        1 => DOOR2_TILES.as_ptr().add(offset),
        2 => DOOR3_TILES.as_ptr().add(offset),
        _ => DOOR4_TILES.as_ptr().add(offset),
    }
}

// ── Constants ─────────────────────────────────────────────────────────────

const NBDFRAMES: u8 = 0x18;
const NBSFRAMES: u8 = 0x07;
const WINSZX: u8 = 0x80;
const WINSZY: u8 = 0x50;
const MINWINX: u8 = MAXWNDPOSX - WINSZX + 1;
const MINWINY: u8 = MAXWNDPOSY - WINSZY + 1;
const MAXWINX: u8 = MAXWNDPOSX;
const MAXWINY: u8 = MAXWNDPOSY;
const FADESTEP: u8 = 0x10;
const STARTFADE: u8 = 0x06 * FADESTEP;

const CLOSED: u8 = 0x00;
const OPENING: u8 = 0x01;
const OPENED: u8 = 0x02;
const CLOSING: u8 = 0x03;


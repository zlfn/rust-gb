// ── Functions ─────────────────────────────────────────────────────────────

unsafe fn fade() {
    if COLOR == 0 { return; }
    match COLOR {
        x if x == STARTFADE || x == STARTFADE - 4 * FADESTEP => BGP_REG.write(0xF9),
        x if x == STARTFADE - FADESTEP || x == STARTFADE - 3 * FADESTEP => BGP_REG.write(0xFE),
        x if x == STARTFADE - 2 * FADESTEP => BGP_REG.write(0xFF),
        x if x == STARTFADE - 5 * FADESTEP => BGP_REG.write(0xE4),
        _ => {}
    }
    COLOR -= 1;
}

unsafe fn scroll() {
    // Update background
    BPOSX.w = BPOSX.w.wrapping_add(BSPX.w);
    BPOSY.w = BPOSY.w.wrapping_add(BSPY.w);
    SCX_REG.write(BPOSX.b.h);
    SCY_REG.write(BPOSY.b.h);

    // Update window
    WPOSX.w = WPOSX.w.wrapping_add(WSPX.w);
    WPOSY.w = WPOSY.w.wrapping_add(WSPY.w);
    if WPOSX.b.h >= MAXWINX {
        WPOSX.b.h = MAXWINX;
        WSPX.w = (-(WSPX.w as i16)) as u16;
    } else if WPOSX.b.h <= MINWINX {
        WPOSX.b.h = MINWINX;
        WSPX.w = (-(WSPX.w as i16)) as u16;
    }
    WX_REG.write(WPOSX.b.h);
    if WPOSY.b.h >= MAXWINY {
        WPOSY.b.h = MAXWINY;
        WSPY.w = (-(WSPY.w as i16)) as u16;
    } else if WPOSY.b.h <= MINWINY {
        WPOSY.b.h = MINWINY;
        WSPY.w = (-(WSPY.w as i16)) as u16;
    }
    WY_REG.write(WPOSY.b.h);

    // Update sprite
    SPOSX.w = SPOSX.w.wrapping_add(SSPX.w);
    SPOSY.w = SPOSY.w.wrapping_add(SSPY.w);
    place_sprite();
}

unsafe fn door() {
    if DOORSTATE == OPENING {
        DOORPOS += 1;
        set_win_tiles(2, 2, 12, 6, film(DOORPOS));
        if DOORPOS == NBDFRAMES { DOORSTATE = OPENED; }
    } else if DOORSTATE == CLOSING {
        DOORPOS -= 1;
        set_win_tiles(2, 2, 12, 6, film(DOORPOS));
        if DOORPOS == 0 { DOORSTATE = CLOSED; }
    }
}

unsafe fn animate_sprite() {
    if (TIME & 0x07) == 0 {
        SFRAME += 1;
        if SFRAME == NBSFRAMES { SFRAME = 0; }
        tile_sprite();
    }
}

unsafe fn tile_sprite() {
    let s = (SFRAME << 1) as usize;
    set_sprite_tile(0, EARTH_TILES[s]);
    set_sprite_tile(1, EARTH_TILES[s + 1]);
}

unsafe fn place_sprite() {
    move_sprite(0, SPOSX.b.h, SPOSY.b.h);
    move_sprite(1, SPOSX.b.h + 8, SPOSY.b.h);
}

#[gb_rt::entry]
fn main() -> ! {
    unsafe {
        gbdk_sys::init();

        disable_interrupts();
        display_off();
        LCDC_REG.write(
            LCDCF_OFF | LCDCF_WIN9C00 | LCDCF_WINON | LCDCF_BG8800 |
            LCDCF_BG9800 | LCDCF_OBJ16 | LCDCF_OBJON | LCDCF_BGON
        );

        DOORSTATE = CLOSED;

        BGP_REG.write(0xE4);
        OBP0_REG.write(0xE4);
        OBP1_REG.write(0xE4);

        // Initialize the background
        set_bkg_data(0xFC, 0x04, STD_DATA.as_ptr());
        set_bkg_data(0x00, 0x2D, BKG_DATA.as_ptr());
        for i in (0u8..32).step_by(8) {
            for j in (0u8..32).step_by(8) {
                set_bkg_tiles(i, j, 8, 8, BKG_TILES.as_ptr());
            }
        }
        BPOSX.w = 0;
        SCX_REG.write(0);
        BPOSY.w = 0;
        SCY_REG.write(0);
        BSPX.w = 0xFF00;
        BSPY.w = 0x0080;

        // Initialize the window
        set_win_data(0x80, 0x21, FRAME_DATA.as_ptr());
        set_win_tiles(0, 0, 16, 10, FRAME_TILES.as_ptr());
        set_win_tiles(2, 2, 12, 6, DOOR1_TILES.as_ptr());
        WPOSX.b.h = MAXWINX;
        WPOSX.b.l = 0;
        WX_REG.write(MAXWINX);
        WPOSY.b.h = MAXWINY;
        WPOSY.b.l = 0;
        WY_REG.write(MAXWINY);
        WSPX.w = 0xFF80;
        WSPY.w = 0xFFC0;

        // Initialize the sprite
        set_sprite_data(0x00, 0x1C, EARTH_DATA.as_ptr());
        set_sprite_prop(0, 0x00);
        set_sprite_prop(1, 0x00);
        SFRAME = 0;
        SPOSX.w = 0x1000;
        SPOSY.w = 0x1000;
        SSPX.w = 0x0040;
        SSPY.w = 0x0040;
        tile_sprite();
        place_sprite();

        display_on();
        enable_interrupts();

        loop {
            for _ in 0..4 {
                vsync();
            }
            TIME = TIME.wrapping_add(1);
            fade();
            door();
            scroll();
            animate_sprite();
            let i = joypad();
            if i & J_B != 0 {
                if i & J_UP != 0    { BSPY.w = BSPY.w.wrapping_sub(0x0010); }
                if i & J_DOWN != 0  { BSPY.w = BSPY.w.wrapping_add(0x0010); }
                if i & J_LEFT != 0  { BSPX.w = BSPX.w.wrapping_sub(0x0010); }
                if i & J_RIGHT != 0 { BSPX.w = BSPX.w.wrapping_add(0x0010); }
            } else if i & J_A != 0 {
                if i & J_UP != 0    { WSPY.w = WSPY.w.wrapping_sub(0x0010); }
                if i & J_DOWN != 0  { WSPY.w = WSPY.w.wrapping_add(0x0010); }
                if i & J_LEFT != 0  { WSPX.w = WSPX.w.wrapping_sub(0x0010); }
                if i & J_RIGHT != 0 { WSPX.w = WSPX.w.wrapping_add(0x0010); }
            } else {
                if i & J_SELECT != 0 { COLOR = STARTFADE; }
                if i & J_START != 0 {
                    if DOORSTATE == CLOSED {
                        DOORSTATE = OPENING;
                        DOORPOS = 0;
                    } else if DOORSTATE == OPENED {
                        DOORSTATE = CLOSING;
                        DOORPOS = NBDFRAMES;
                    }
                }
                if i & J_UP != 0    { SSPY.w = SSPY.w.wrapping_sub(0x0010); }
                if i & J_DOWN != 0  { SSPY.w = SSPY.w.wrapping_add(0x0010); }
                if i & J_LEFT != 0  { SSPX.w = SSPX.w.wrapping_sub(0x0010); }
                if i & J_RIGHT != 0 { SSPX.w = SSPX.w.wrapping_add(0x0010); }
            }
        }
    }
}

#[panic_handler]
fn panic(_info: &core::panic::PanicInfo) -> ! {
    loop {}
}

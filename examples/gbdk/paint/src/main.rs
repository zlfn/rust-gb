// Convenience accessors for global state
macro_rules! g {
    ($v:ident) => { *$v.get() };
}
macro_rules! dbuf {
    ($idx:expr) => { (*DATA_BUFFER.get()).get_unchecked_mut($idx) };
}

unsafe fn set_cursor() {
    let cur = &CURSORS[g!(CURRENT_CURSOR) as usize];
    let mut i: u8 = 0;
    let mut x: u8 = 0;
    while x < cur.w {
        let mut y: u8 = 0;
        while y < cur.h {
            set_sprite_data(i, 1, CURSORS_DATA[(cur.data_idx + i) as usize].as_ptr());
            set_sprite_tile(i, i);
            set_sprite_prop(i, 0x10);
            i += 1;
            y += 1;
        }
        x += 1;
    }
    while i < 4 {
        move_sprite(i, 0, 0);
        i += 1;
    }
}

unsafe fn move_cursor() {
    let cur = &CURSORS[g!(CURRENT_CURSOR) as usize];
    let mut x: u8 = 0;
    while x < cur.w {
        let mut y: u8 = 0;
        while y < cur.h {
            move_sprite(
                (x << 1) + y,
                g!(CURSOR_X).wrapping_add(8).wrapping_sub(cur.hot_x).wrapping_add(x << 3),
                g!(CURSOR_Y).wrapping_add(16).wrapping_sub(cur.hot_y).wrapping_add(y << 3),
            );
            y += 1;
        }
        x += 1;
    }
}

unsafe fn move_menu_cursor() {
    let icon = &ICONS[g!(MENU_CURSOR_POS) as usize];
    move_sprite(
        0,
        ((icon.x + icon.w) << 3) + 4,
        ((icon.y + icon.h) << 3) + 12,
    );
}

unsafe fn set_icon(icon: u8, selected: u8) {
    let ic = &ICONS[icon as usize];
    let mut x: u8 = 0;
    while x < ic.w {
        let mut y: u8 = 0;
        while y < ic.h {
            let index = (ic.data_idx as u16) + ((x as u16) << 1) + y as u16;
            let src = if selected != 0 {
                SELECTED_DATA[index as usize].as_ptr()
            } else {
                DATA[index as usize].as_ptr()
            };
            switch_data(
                ic.x + x, ic.y + y,
                src as *mut u8,
                dbuf!(index as usize).as_mut_ptr(),
            );
            y += 1;
        }
        x += 1;
    }
}

unsafe fn change_icon(icon: u8, selected: u8) {
    let ic = &ICONS[icon as usize];
    let mut x: u8 = 0;
    while x < ic.w {
        let mut y: u8 = 0;
        while y < ic.h {
            let index = (ic.data_idx as u16) + ((x as u16) << 1) + y as u16;
            let src = if selected != 0 {
                SELECTED_DATA[index as usize].as_ptr()
            } else {
                DATA[index as usize].as_ptr()
            };
            switch_data(ic.x + x, ic.y + y, src as *mut u8, core::ptr::null_mut());
            y += 1;
        }
        x += 1;
    }
}

unsafe fn reset_icon(icon: u8) {
    let ic = &ICONS[icon as usize];
    let mut x: u8 = 0;
    while x < ic.w {
        let mut y: u8 = 0;
        while y < ic.h {
            let index = (ic.data_idx + (x << 1) + y) as usize;
            switch_data(
                ic.x + x, ic.y + y,
                dbuf!(index).as_mut_ptr(),
                core::ptr::null_mut(),
            );
            y += 1;
        }
        x += 1;
    }
}

unsafe fn splash() {
    *CURSOR_X.get() = 40;
    *CURSOR_Y.get() = 50;
    *CURRENT_CURSOR.get() = PEN;
    set_cursor();
    move_cursor();
    LCDC_REG.write(LCDC_REG.read() | LCDCF_OBJON);

    while g!(CURSOR_X) < 120 { vsync(); move_cursor(); plot(g!(CURSOR_X), g!(CURSOR_Y), BLACK, SOLID); g!(CURSOR_X) += 1; }
    while g!(CURSOR_Y) < 94  { vsync(); move_cursor(); plot(g!(CURSOR_X), g!(CURSOR_Y), BLACK, SOLID); g!(CURSOR_Y) += 1; }
    while g!(CURSOR_X) > 40  { vsync(); move_cursor(); plot(g!(CURSOR_X), g!(CURSOR_Y), BLACK, SOLID); g!(CURSOR_X) -= 1; }
    while g!(CURSOR_Y) > 50  { vsync(); move_cursor(); plot(g!(CURSOR_X), g!(CURSOR_Y), BLACK, SOLID); g!(CURSOR_Y) -= 1; }

    *CURSOR_X.get() = 80;
    *CURSOR_Y.get() = 72;
    *CURRENT_CURSOR.get() = FILL;
    set_cursor();
    move_cursor();

    let mut y: u8 = 51;
    while y < 94 {
        let mut x: u8 = 41;
        while x < 120 {
            plot(x, y, LTGREY, SOLID);
            x += 1;
        }
        y += 1;
    }
}

unsafe fn menu() {
    let mut slowdown: u8 = 50;

    let mut i: u8 = 0;
    while i < NB_TOOLS as u8 {
        set_icon(i,
            if i == FIRST_TOOL + g!(CURRENT_TOOL)
                || i == FIRST_COLOR + g!(CURRENT_COLOR)
                || i == FIRST_MODE + g!(CURRENT_MODE) { SELECTED } else { UNSELECTED });
        i += 1;
    }

    let mut cursor = g!(CURRENT_CURSOR);
    *CURRENT_CURSOR.get() = ARROW;
    set_cursor();
    move_menu_cursor();
    LCDC_REG.write(LCDC_REG.read() | LCDCF_OBJON);
    waitpadup();

    loop {
        vsync();
        let key = joypad();
        if (key & (J_UP | J_DOWN | J_LEFT | J_RIGHT)) != 0 {
            if (key & J_UP) != 0    { *MENU_CURSOR_POS.get() = ICONS[g!(MENU_CURSOR_POS) as usize].up; }
            if (key & J_DOWN) != 0  { *MENU_CURSOR_POS.get() = ICONS[g!(MENU_CURSOR_POS) as usize].down; }
            if (key & J_LEFT) != 0  { *MENU_CURSOR_POS.get() = ICONS[g!(MENU_CURSOR_POS) as usize].left; }
            if (key & J_RIGHT) != 0 { *MENU_CURSOR_POS.get() = ICONS[g!(MENU_CURSOR_POS) as usize].right; }
            move_menu_cursor();
            while slowdown > 0 && key == joypad() { vsync(); slowdown -= 1; }
            slowdown = 10;
        } else {
            slowdown = 50;
        }
        if (key & J_A) != 0 {
            if g!(MENU_CURSOR_POS) <= LAST_TOOL {
                if g!(MENU_CURSOR_POS) != g!(CURRENT_TOOL) {
                    change_icon(g!(CURRENT_TOOL), UNSELECTED);
                    *CURRENT_TOOL.get() = g!(MENU_CURSOR_POS);
                    change_icon(g!(CURRENT_TOOL), SELECTED);
                    cursor = ICONS[g!(CURRENT_TOOL) as usize].cursor;
                }
            } else if g!(MENU_CURSOR_POS) >= FIRST_COLOR && g!(MENU_CURSOR_POS) <= LAST_COLOR {
                if g!(MENU_CURSOR_POS) != FIRST_COLOR + g!(CURRENT_COLOR) {
                    change_icon(FIRST_COLOR + g!(CURRENT_COLOR), UNSELECTED);
                    *CURRENT_COLOR.get() = g!(MENU_CURSOR_POS) - FIRST_COLOR;
                    change_icon(FIRST_COLOR + g!(CURRENT_COLOR), SELECTED);
                }
            } else if g!(MENU_CURSOR_POS) >= FIRST_MODE && g!(MENU_CURSOR_POS) <= LAST_MODE {
                if g!(MENU_CURSOR_POS) != FIRST_MODE + g!(CURRENT_MODE) {
                    change_icon(FIRST_MODE + g!(CURRENT_MODE), UNSELECTED);
                    *CURRENT_MODE.get() = g!(MENU_CURSOR_POS) - FIRST_MODE;
                    change_icon(FIRST_MODE + g!(CURRENT_MODE), SELECTED);
                }
            }
        }
        if key == J_SELECT { break; }
    }
    waitpadup();

    i = 0;
    while i < NB_TOOLS as u8 {
        reset_icon(i);
        i += 1;
    }
    LCDC_REG.write(LCDC_REG.read() & !LCDCF_OBJON);
    *CURRENT_CURSOR.get() = cursor;
}

unsafe fn run() {
    let mut slowdown: u8 = 10;
    let mut drawn: u8 = 0;
    let mut erased: u8 = 0;

    set_cursor();
    move_cursor();
    LCDC_REG.write(LCDC_REG.read() | LCDCF_OBJON);

    loop {
        vsync();
        let key = joypad();
        if (key & (J_UP | J_DOWN | J_LEFT | J_RIGHT)) != 0 {
            if (key & J_UP) != 0 && g!(CURSOR_Y) > 0       { g!(CURSOR_Y) -= 1; }
            if (key & J_DOWN) != 0 && g!(CURSOR_Y) < 143    { g!(CURSOR_Y) += 1; }
            if (key & J_LEFT) != 0 && g!(CURSOR_X) > 0      { g!(CURSOR_X) -= 1; }
            if (key & J_RIGHT) != 0 && g!(CURSOR_X) < 159   { g!(CURSOR_X) += 1; }
            move_cursor();
            while slowdown > 0 && key == joypad() { vsync(); slowdown -= 1; }
            slowdown = 1;
            drawn = 0;
            erased = 0;
        } else {
            slowdown = 10;
        }
        if (key & J_SELECT) != 0 {
            LCDC_REG.write(LCDC_REG.read() & !LCDCF_OBJON);
            menu();
            set_cursor();
            move_cursor();
            LCDC_REG.write(LCDC_REG.read() | LCDCF_OBJON);
        }
        if (key & (J_A | J_B)) == J_A {
            if drawn == 0 {
                drawn += 1;
                plot(g!(CURSOR_X), g!(CURSOR_Y), COLORS[g!(CURRENT_COLOR) as usize], MODES[g!(CURRENT_MODE) as usize]);
            }
        } else {
            drawn = 0;
        }
        if (key & (J_A | J_B)) == J_B {
            if erased == 0 {
                erased += 1;
                plot(g!(CURSOR_X), g!(CURSOR_Y), WHITE, SOLID);
            }
        } else {
            erased = 0;
        }
    }
}

#[unsafe(no_mangle)]
pub extern "C" fn main() {
    unsafe {
        gbdk_sys::init();
        OBP1_REG.write(0xE0);

        splash();

        *CURRENT_TOOL.get() = 0;
        *CURRENT_COLOR.get() = BLACK;
        *CURRENT_MODE.get() = SOLID;
        *CURRENT_CURSOR.get() = PEN;
        *MENU_CURSOR_POS.get() = 0;
        *CURSOR_X.get() = 80;
        *CURSOR_Y.get() = 72;

        run();
    }
}

